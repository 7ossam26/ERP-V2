import api from "./apiClient";

/**
 * Field mapping between frontend and backend
 * Frontend uses simplified field names, backend uses database schema names
 */

// Map frontend employee data to backend format
const toBackend = (frontendData) => {
  const backendData = {
    name: frontendData.name,
    position: frontendData.title || frontendData.position,
    branch: frontendData.branch,
    phoneNumber: frontendData.phone || frontendData.phoneNumber,
    nationalId: frontendData.nationalId || null,
    workingDaysPerMonth: parseInt(
      frontendData.workDays || frontendData.workingDaysPerMonth || 26
    ),
    workingHoursPerDay: parseFloat(
      frontendData.workHours || frontendData.workingHoursPerDay || 8
    ),
    weeklyHoliday:
      frontendData.weekend || frontendData.weeklyHoliday || "Friday",
    salary: parseFloat(frontendData.salary),
  };

  // Remove id if it's the placeholder value
  if (frontendData.id && frontendData.id !== "#") {
    backendData.id = frontendData.id;
  }

  return backendData;
};

// Map backend employee data to frontend format
const toFrontend = (backendData) => {
  return {
    id: backendData.id,
    name: backendData.name,
    title: backendData.position,
    branch: backendData.branch,
    phone: backendData.phoneNumber,
    nationalId: backendData.nationalId || "",
    workDays: backendData.workingDaysPerMonth.toString(),
    workHours: backendData.workingHoursPerDay.toString(),
    weekend: backendData.weeklyHoliday,
    salary: backendData.salary.toString(),
    createdAt: backendData.createdAt,
    updatedAt: backendData.updatedAt,
  };
};

/**
 * Employee API Service
 * Provides CRUD operations for employees with automatic field mapping
 */
export const employeeService = {
  /**
   * Get all employees
   * @returns {Promise<Array>} Array of employees in frontend format
   */
  getAll: async () => {
    const employees = await api.get("/employees");
    return employees.map(toFrontend);
  },

  /**
   * Get employee by ID
   * @param {number} id - Employee ID
   * @returns {Promise<Object>} Employee in frontend format
   */
  getById: async (id) => {
    const employee = await api.get(`/employees/${id}`);
    return toFrontend(employee);
  },

  /**
   * Create a new employee
   * @param {Object} employeeData - Employee data in frontend format
   * @returns {Promise<Object>} Created employee in frontend format
   */
  create: async (employeeData) => {
    const backendData = toBackend(employeeData);
    delete backendData.id; // Ensure ID is generated by backend
    const createdEmployee = await api.post("/employees", backendData);
    return toFrontend(createdEmployee);
  },

  /**
   * Update an existing employee
   * @param {number} id - Employee ID
   * @param {Object} updates - Updated employee data in frontend format
   * @returns {Promise<Object>} Updated employee in frontend format
   */
  update: async (id, updates) => {
    const backendData = toBackend(updates);
    const updatedEmployee = await api.put(`/employees/${id}`, backendData);
    return toFrontend(updatedEmployee);
  },

  /**
   * Delete an employee
   * @param {number} id - Employee ID
   * @returns {Promise<boolean>} Success status
   */
  delete: async (id) => {
    await api.delete(`/employees/${id}`);
    return true;
  },
};
